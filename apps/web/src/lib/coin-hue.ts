/**
 * Тон кружка монеты — угол на цветовом круге (0–359) из символа. Хэш детерминированный: один символ даёт один
 * тон на любом экране и после перезагрузки. Множитель 31 — обычный полиномиальный хэш строки; шаг 137° (золотой
 * угол) разводит соседние значения хэша по кругу, чтобы похожие символы (BTC, BCH) не получали похожий тон.
 */
export function coinHue(symbol: string): number {
  let hash = 0;
  for (const char of symbol.toUpperCase()) hash = (hash * 31 + (char.codePointAt(0) ?? 0)) % 360;
  return (hash * 137) % 360;
}
