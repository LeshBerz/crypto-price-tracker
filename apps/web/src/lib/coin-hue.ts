/**
 * Тон кружка монеты — угол на цветовом круге (0–359) из символа. Хэш детерминированный: один символ даёт один
 * тон на любом экране и после перезагрузки. Алгоритм — FNV-1a (32 бита): у него сильное перемешивание, поэтому
 * символы, отличающиеся одной буквой (BTC и BCH, ETH и ETC), расходятся по кругу, а не встают рядом.
 * `Math.imul` — умножение 32-битных целых без потери точности, `>>> 0` — приведение к беззнаковому.
 */
export function coinHue(symbol: string): number {
  let hash = 2166136261;
  for (const char of symbol.toUpperCase()) {
    hash ^= char.codePointAt(0) ?? 0;
    hash = Math.imul(hash, 16777619) >>> 0;
  }
  return hash % 360;
}
